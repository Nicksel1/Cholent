// Automatic spelling for names that aren't in the list yet (new locations).
const MAP = { "א": "a", "ב": "b", "ג": "g", "ד": "d", "ה": "h", "ו": "o", "ז": "z", "ח": "ch", "ט": "t", "י": "i", "כ": "k", "ך": "ch", "ל": "l", "מ": "m", "ם": "m", "נ": "n", "ן": "n", "ס": "s", "ע": "a", "פ": "p", "ף": "f", "צ": "tz", "ץ": "tz", "ק": "k", "ר": "r", "ש": "sh", "ת": "t" };
export function autoEn(name) {
  return name.normalize("NFKD").replace(/[֑-ׇ]/g, "")
    .replace(/צ['׳]/g, "ch").replace(/ג['׳]/g, "j").replace(/ז['׳]/g, "zh").replace(/טש/g, "ch")
    .replace(/וו/g, "v").replace(/יי/g, "ei")
    .replace(/[א-ת]/g, (c) => MAP[c] || "").replace(/['׳"״]/g, "").replace(/\s+/g, " ").trim();
}
